import trimesh
import numpy as np
import open3d as o3d
import sys

argv = sys.argv
argc = len(argv)

print('%s extracts point clound and meshes from click3r demo glb' % argv[0])
print('[usage] python %s <glb generated by click3r on-line demo>' % argv[0])

if argc < 2:
    quit()

scene = trimesh.load(argv[1])
for geometry_name, geometry in scene.geometry.items():
    print(geometry_name)
    if isinstance(geometry, trimesh.Trimesh):
        print(f'{geometry_name} はTrimeshです')
        mesh = o3d.geometry.TriangleMesh()
        mesh.vertices = o3d.utility.Vector3dVector(np.asarray(geometry.vertices))
        mesh.triangles = o3d.utility.Vector3iVector(np.asarray(geometry.faces))
        dst_path = '%s.ply' % geometry_name
        o3d.io.write_triangle_mesh(dst_path, mesh)
        print('save %s' % dst_path)

    elif isinstance(geometry, trimesh.PointCloud):
        print(f'{geometry_name} は Point Cloudです')
        pcd = o3d.geometry.PointCloud()
        pcd.points = o3d.utility.Vector3dVector(geometry.vertices)
        dst_path = '%s.ply' % geometry_name
        o3d.io.write_point_cloud(dst_path, pcd)
        print('save %s' % dst_path)